/* OR Supply Relay -- lock-screen alerts (browser side).
   Load AFTER the main app script, as the last thing in index.html:
       <script src="push.js"></script>
   It adds a one-line "Turn on lock-screen alerts" strip at the top of both
   views, and needs nothing else changed in the app. It reads the app's own
   globals (state, me, sb, SITES, inZone, toast, render, refresh).

   Two independent switches per phone, because one phone can be both:
     tech view      -> alert me when a new request comes in for my coverage area
     request view   -> alert me when a tech picks up my request */
(function () {
  "use strict";

  /* PASTE the VAPID *public* key here (the one generated by
     `npx web-push generate-vapid-keys`). The private key never goes in this file. */
  const VAPID_PUBLIC_KEY = "BBCDiRttSDactgtr0-1iIb3-uXgVZpWJKawo3OpVCC7Ze5qHsscjINYy4bOXOywfI5KqcA2brLDWcjptIMg0oHQ";

  if (typeof state === "undefined" || typeof sb === "undefined") return;   // not the relay app

  const supported = "serviceWorker" in navigator && "PushManager" in window && "Notification" in window;
  const isIOS = /iPhone|iPad|iPod/.test(navigator.userAgent) ||
                (navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1);
  const standalone = matchMedia("(display-mode: standalone)").matches || navigator.standalone === true;

  let prefs;
  try { prefs = JSON.parse(localStorage.getItem("or-push")) || {}; } catch (_) { prefs = {}; }
  const savePrefs = () => localStorage.setItem("or-push", JSON.stringify(prefs));

  const b64ToBytes = s => {
    const pad = "=".repeat((4 - s.length % 4) % 4);
    const raw = atob((s + pad).replace(/-/g, "+").replace(/_/g, "/"));
    return Uint8Array.from(raw, c => c.charCodeAt(0));
  };

  /* The coverage area is stored on the subscription as "SITE|AREA" pairs, so
     the server never needs its own copy of ZONES. "ALL" becomes "*". */
  function coveredAreas() {
    const all = [], hit = [];
    SITES.forEach(s => s.areas.forEach(a => {
      all.push(1);
      if (inZone(state.filter, { site: s.id, area: a.id })) hit.push(s.id + "|" + a.id);
    }));
    return hit.length === all.length ? ["*"] : hit;
  }

  async function save(sub, tech, claim) {
    const j = sub.toJSON();
    const { error } = await sb.rpc("save_push_subscription", {
      p_endpoint: j.endpoint, p_p256dh: j.keys.p256dh, p_auth: j.keys.auth,
      p_device_id: me, p_tech: tech, p_claim: claim,
      p_areas: tech ? coveredAreas() : []
    });
    if (error) throw error;
  }

  /* Make the browser subscription and the database row match the switches. */
  async function sync() {
    try {
      const reg = await navigator.serviceWorker.ready;
      let sub = await reg.pushManager.getSubscription();
      if (!prefs.tech && !prefs.claim) {
        if (sub) { await save(sub, false, false); await sub.unsubscribe(); }
        return true;
      }
      const opts = { userVisibleOnly: true, applicationServerKey: b64ToBytes(VAPID_PUBLIC_KEY) };
      try {
        sub = sub || await reg.pushManager.subscribe(opts);
      } catch (e) {
        if (e.name !== "InvalidStateError") throw e;
        if (sub) await sub.unsubscribe();           // old subscription used a different key
        sub = await reg.pushManager.subscribe(opts);
      }
      await save(sub, !!prefs.tech, !!prefs.claim);
      return true;
    } catch (e) {
      console.error("push sync failed", e);
      toast("Couldn't set up alerts: " + (e && e.message ? e.message : e));
      return false;
    }
  }

  /* ---------- the strip ---------- */
  const css = document.createElement("style");
  css.textContent = `
    .pushbar { margin: 12px 14px 0; padding: 10px 12px; border-radius: 12px;
      background: var(--surface); border: 1px solid var(--line);
      display: flex; align-items: center; gap: 10px;
      font-size: 13.5px; color: var(--ink-dim); }
    .pushbar[hidden] { display: none; }
    .pushbar.on { border-color: var(--drape); }
    .pushbar.on span { color: var(--ink); }
    .pushbar span { flex: 1; }
    .pushbar button { min-height: 40px; padding: 0 13px; border-radius: 9px;
      background: var(--surface-2); font-size: 13.5px; font-weight: 600; color: var(--ink); }
    .pushbar button.go { background: var(--drape); color: #fff; }
    .sheet ol { margin: 0 0 16px; padding-left: 20px; font-size: 15px; line-height: 1.55; }`;
  document.head.appendChild(css);

  const bar = document.createElement("div");
  bar.className = "pushbar"; bar.hidden = true;

  const row = (text, buttons) => `<span>${text}</span>${buttons || ""}`;
  const btn = (act, label, cls) => `<button ${cls ? `class="${cls}" ` : ""}data-push="${act}">${label}</button>`;
  const kindNow = () => state.role === "tech" ? "tech" : "claim";

  function paint() {
    const kind = kindNow();
    let html = "", on = false;
    if (!supported) {
      // iPhone only exposes push once the app is on the Home Screen.
      if (isIOS && !standalone) {
        html = row("Add this app to your Home Screen to get lock-screen alerts.", btn("ios", "How", "go"));
      }
    } else if (Notification.permission === "denied") {
      html = row("Alerts are blocked for this app. Allow notifications for it in your phone's Settings.");
    } else if (prefs[kind]) {
      on = true;
      html = row("Lock-screen alerts are on" +
        (kind === "tech" ? " for new requests" : " when a tech picks up your request"),
        btn("test", "Test") + btn("off", "Turn off"));
    } else {
      html = row(kind === "tech"
        ? "Get a lock-screen alert when a request comes in for your area."
        : "Get a lock-screen alert when a tech picks up your request.",
        btn("on", "Turn on", "go"));
    }
    bar.className = "pushbar" + (on ? " on" : "");
    if (bar.dataset.h !== html) { bar.innerHTML = html; bar.dataset.h = html; }
    bar.hidden = !html;
  }

  function iosHelp() {
    const s = document.getElementById("sheet");
    s.innerHTML = `
      <h3>Add to Home Screen first</h3>
      <p>iPhone only allows lock-screen alerts for apps on the Home Screen.</p>
      <ol>
        <li>In Safari, tap the Share button (square with an arrow).</li>
        <li>Choose <b>Add to Home Screen</b>, then <b>Add</b>.</li>
        <li>Open <b>Supply Relay</b> from the new icon, and tap <b>Turn on</b>.</li>
      </ol>
      <button class="cancel" data-cancel="1">Got it</button>`;
    document.getElementById("scrim").classList.add("open");
    s.onclick = ev => { if (ev.target.closest("button")) closeSheet(); };
  }

  async function turnOn(kind) {
    if (VAPID_PUBLIC_KEY.indexOf("PASTE") === 0) { toast("Alerts aren't set up yet"); return; }
    let perm = Notification.permission;
    if (perm === "default") perm = await Notification.requestPermission();   // must follow the tap
    if (perm !== "granted") { toast("Alerts are blocked"); paint(); return; }
    prefs[kind] = true; savePrefs();
    if (await sync()) toast("Lock-screen alerts on");
    else { prefs[kind] = false; savePrefs(); }
    paint();
  }

  async function turnOff(kind) {
    prefs[kind] = false; savePrefs();
    await sync();
    toast("Alerts off");
    paint();
  }

  /* Shows a notification locally. It proves this phone can display one, not
     that the server path works -- a real request from another phone does that. */
  async function test() {
    const reg = await navigator.serviceWorker.ready;
    await reg.showNotification("Test alert", {
      body: "Lock your phone and send a real request to see one arrive.",
      icon: "icon-192.png", tag: "test"
    });
  }

  bar.addEventListener("click", async ev => {
    const b = ev.target.closest("button"); if (!b) return;
    const kind = kindNow();
    ev.stopPropagation();
    if (b.dataset.push === "ios") iosHelp();
    else if (b.dataset.push === "on") await turnOn(kind);
    else if (b.dataset.push === "off") await turnOff(kind);
    else if (b.dataset.push === "test") await test();
  });

  /* The app rebuilds <main> on every render, which would delete the strip,
     so put it back right after each one. */
  const baseRender = render;
  render = function () {
    baseRender();
    document.getElementById("main").prepend(bar);
    paint();
  };

  /* ---------- wiring ---------- */
  const goView = v => {
    state.role = v === "tech" ? "tech" : "clin";
    localStorage.setItem("or-role", state.role);
    refresh();
  };

  if (supported) {
    navigator.serviceWorker.register("sw.js").then(() => {
      // Re-sync on every open: phones rotate subscriptions, and the coverage
      // area may have changed since the last time.
      if (Notification.permission === "granted" && (prefs.tech || prefs.claim)) sync();
    }).catch(e => console.error("service worker failed", e));
    navigator.serviceWorker.addEventListener("message", e => {
      if (e.data && e.data.type === "push-open") goView(e.data.view);
    });
    // Changing the coverage zone changes which requests should alert this phone.
    const zs = document.getElementById("zoneSel");
    if (zs) zs.addEventListener("change", () => { if (prefs.tech) sync(); });
  }

  const v = new URLSearchParams(location.search).get("view");   // set by a tapped notification
  if (v === "tech" || v === "clin") goView(v);

  render();
})();
